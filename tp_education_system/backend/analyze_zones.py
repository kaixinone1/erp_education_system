from docx import Document
doc = Document(r'D:\erp_thirteen\数据库信息\模板\职工退休呈报表.docx')

print('='*80)
print('退休呈报表分区分析')
print('='*80)

table = doc.tables[1]
print(f'\n主表格尺寸: {len(table.rows)}行 × {len(table.columns)}列\n')

# 详细打印每一行
for r_idx, row in enumerate(table.rows):
    cells = []
    for c_idx, cell in enumerate(row.cells):
        text = cell.text.replace('\n', ' ').strip()
        if text:
            cells.append(f'[{c_idx}]{text[:15]}')
    if cells:
        print(f'行{r_idx:2d}: {" | ".join(cells)}')
    else:
        print(f'行{r_idx:2d}: (空白行)')

